#!/usr/bin/env python3
"""Apply a registered, public Kakao native app key to dev only."""
from pathlib import Path
import re, sys
root = Path(__file__).resolve().parents[1]
if len(sys.argv) != 2 or not re.fullmatch(r'[0-9a-fA-F]{32}', sys.argv[1]):
    raise SystemExit('Usage: python3 tool/configure_dev_kakao.py <32-character-native-app-key>')
key = sys.argv[1].lower()
if key == 'ec26372ba0fec512e3f8a00d0295d35c':
    raise SystemExit('Use a separate dev native key to avoid callback collisions.')
scheme = 'kakao' + key
p = root / 'lib/core/dev_kakao.dart'
p.write_text('// Generated by tool/configure_dev_kakao.py; native keys are public app identifiers.\n'
             + "const devKakaoNativeAppKey = '" + key + "';\n")
p = root / 'ios/Runner.xcodeproj/project.pbxproj'
s = p.read_text()
# Only replace the development scheme; preserve the production scheme.
s = re.sub(r'KAKAO_URL_SCHEME = (?:"?luckylog-dev-kakao"?|kakao[0-9a-f]{32});',
           lambda m: m.group(0) if 'ec26372ba0fec512e3f8a00d0295d35c' in m.group(0)
           else 'KAKAO_URL_SCHEME = ' + scheme + ';', s)
p.write_text(s)
p = root / 'android/app/build.gradle.kts'
s = p.read_text()
a = s.index('create("dev")'); b = s.index('    buildTypes {', a)
part = re.sub(r'manifestPlaceholders\["kakaoScheme"\] = "[^"]+"',
              'manifestPlaceholders["kakaoScheme"] = "' + scheme + '"', s[a:b])
p.write_text(s[:a] + part + s[b:])
print('Updated dev Kakao key and iOS/Android callback schemes. Production unchanged.')
